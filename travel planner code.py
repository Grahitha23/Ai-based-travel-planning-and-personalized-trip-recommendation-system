# -----------------------------
# Travel Planner Function
# -----------------------------

def travel_planner(destination, days, budget, interest):

    days = int(days)
    budget = int(budget)

    # Validate input

    if days < 1:
        return "⚠️ Please enter at least 1 day."

    if budget < 0:
        return "⚠️ Please enter a valid budget."


    # -------------------------
    # Filter Destination
    # -------------------------

    places = df[
        df["Destination"] == destination
    ]


    # -------------------------
    # Filter Interest
    # -------------------------

    recommended = places[
        places["Category"] == interest
    ]


    # If no matching interest,
    # use all places

    if recommended.empty:

        recommended = places


    # -------------------------
    # Sort by Rating
    # -------------------------

    recommended = recommended.sort_values(
        "Rating",
        ascending=False
    )


    # -------------------------
    # Select Places
    # -------------------------

    required_places = days * 2

    selected_places = recommended.copy()


    # Add remaining destination places
    # if interest places are not enough

    if len(selected_places) < required_places:

        remaining_places = places[
            ~places["Place"].isin(
                selected_places["Place"]
            )
        ].sort_values(
            "Rating",
            ascending=False
        )

        selected_places = pd.concat([
            selected_places,
            remaining_places
        ])


    # -------------------------
    # Create Itinerary
    # -------------------------

    itinerary = ""

    place_list = selected_places[
        "Place"
    ].tolist()


    # Extra activities for longer trips

    extra_activities = [
        "Local Food Experience",
        "Shopping and Souvenir Visit",
        "Photography and Sightseeing",
        "Relaxation and Leisure Time",
        "Local Market Visit",
        "Cultural Experience",
        "Evening Walk",
        "Local Cafe Experience"
    ]


    place_index = 0
    extra_index = 0


    for day in range(1, days + 1):

        itinerary += f"\n### Day {day}\n"


        # First activity

        if place_index < len(place_list):

            itinerary += (
                f"- Explore {place_list[place_index]}\n"
            )

            place_index += 1

        else:

            activity = extra_activities[
                extra_index % len(extra_activities)
            ]

            itinerary += (
                f"- Enjoy {activity}\n"
            )

            extra_index += 1


        # Second activity

        if place_index < len(place_list):

            itinerary += (
                f"- Explore {place_list[place_index]}\n"
            )

            place_index += 1

        else:

            activity = extra_activities[
                extra_index % len(extra_activities)
            ]

            itinerary += (
                f"- Enjoy {activity}\n"
            )

            extra_index += 1


    # -------------------------
    # Budget Calculation
    # -------------------------

    transportation = 500

    accommodation = days * 1500

    food = days * 700


    # Attractions only from places
    # actually used in the trip

    number_of_place_visits = min(
        days * 2,
        len(selected_places)
    )

    attraction_places = selected_places.head(
        number_of_place_visits
    )

    attractions = attraction_places[
        "Cost"
    ].sum()


    total = (
        transportation
        + accommodation
        + food
        + attractions
    )


    # -------------------------
    # Budget Status
    # -------------------------

    if total <= budget:

        budget_status = (
            f"✅ Within Budget\n\n"
            f"Remaining: ₹{budget - total}"
        )

    else:

        budget_status = (
            f"⚠️ Budget Exceeded\n\n"
            f"Extra Required: ₹{total - budget}"
        )


    # -------------------------
    # Recommended Places
    # -------------------------

    places_text = ""


    for _, row in attraction_places.iterrows():

        places_text += (
            f"📍 {row['Place']} | "
            f"Category: {row['Category']} | "
            f"Rating: {row['Rating']} | "
            f"Cost: ₹{row['Cost']}\n"
        )


    # -------------------------
    # Final Result
    # -------------------------

    result = f"""

# ✈️ Personalized Travel Plan

## 📍 Destination

**{destination}**


## ❤️ Selected Interest

**{interest}**


## 📅 Trip Duration

**{days} Days**

---

## 📌 Recommended Places

{places_text}

---

## 🗓️ Day-wise Itinerary

{itinerary}

---

## 💰 Budget Breakdown

Transportation: ₹{transportation}

Accommodation: ₹{accommodation}

Food: ₹{food}

Attractions: ₹{attractions}


### 💵 Total Estimated Cost: ₹{total}

---

## 📊 Budget Status

{budget_status}

---

### ✈️ Have a wonderful trip!
"""


    return result


